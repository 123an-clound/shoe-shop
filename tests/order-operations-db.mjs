// node tests/order-operations-db.mjs <path-to-pglite/dist/index.js>
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

const { PGlite } = await import(process.argv[2] ? pathToFileURL(process.argv[2]).href : "@electric-sql/pglite");
const db = new PGlite();
try {
  await db.exec(`
    create role anon; create role authenticated; create schema private; create schema auth;
    grant usage on schema private,auth to authenticated;
    create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('test.actor',true),'')::uuid $$;
    create function private.veloce_is_admin() returns boolean language sql as $$ select coalesce(current_setting('test.is_admin',true),'')='true' $$;
    create table public.veloce_admins(user_id uuid, full_name text);
    insert into public.veloce_admins values('00000000-0000-4000-8000-000000000099','Nhân viên kiểm thử');
    create table public.veloce_products(id uuid primary key default gen_random_uuid(),name text,slug text,price bigint,stock integer,images text[],is_published boolean,sizes integer[],colors jsonb,updated_at timestamptz default now());
    create table public.veloce_settings(id integer,coupon_code text,coupon_percent integer,freeship_threshold bigint,shipping_fee bigint);
    insert into public.veloce_settings values(1,'DEMO',10,1000000,30000);
    create table public.veloce_orders(id uuid primary key default gen_random_uuid(),code text unique,customer_name text,customer_phone text,customer_email text,address text,note text,items jsonb,subtotal bigint,discount bigint,shipping_fee bigint,total bigint,status text default 'pending' check(status in('pending','confirmed','shipping','done','cancelled')),created_at timestamptz default now(),updated_at timestamptz default now());
    create function public.veloce_touch_updated_at() returns trigger language plpgsql as $$ begin new.updated_at=now(); return new; end $$;
    create trigger veloce_orders_touch before update on public.veloce_orders for each row execute function public.veloce_touch_updated_at();
    alter table public.veloce_orders enable row level security;
    alter table public.veloce_products enable row level security;
    grant select,update on public.veloce_orders,public.veloce_products to authenticated;
    create policy orders_admin on public.veloce_orders to authenticated using(private.veloce_is_admin()) with check(private.veloce_is_admin());
    create policy products_admin on public.veloce_products to authenticated using(private.veloce_is_admin()) with check(private.veloce_is_admin());
    insert into public.veloce_orders(code,status,created_at) values('OLD','done',now()-interval '2 days');
    select set_config('test.is_admin','true',false);
  `);
  await db.exec(await readFile(new URL("../supabase/migrations/20261012134125_veloce_variant_inventory.sql",import.meta.url),"utf8"));
  await db.exec(await readFile(new URL("../supabase/migrations/20261013073147_veloce_order_operations.sql",import.meta.url),"utf8"));
  await db.exec(await readFile(new URL("../supabase/migrations/20261013082046_veloce_order_event_timestamps.sql",import.meta.url),"utf8"));
  assert.equal((await db.query("select payment_status from public.veloce_orders where code='OLD'")).rows[0].payment_status,null);
  const productId="00000000-0000-4000-8000-000000000001";
  const colors=[{name:"Đen",hex:"#000000",inventory:[{size:39,quantity:10}]}];
  await db.query("insert into public.veloce_products(id,name,slug,price,stock,images,is_published,sizes,colors) values($1,'Giày mẫu','giay-mau',500000,10,'{}',true,'{39}',$2)",[productId,JSON.stringify(colors)]);
  await db.exec("set role anon");
  const checkout=(await db.query("select * from public.veloce_place_order('Khách','0900000000','Địa chỉ',$1)",[JSON.stringify([{product_id:productId,color:"#000000",size:39,quantity:2}])])).rows[0];
  await db.exec("reset role; select set_config('test.actor','00000000-0000-4000-8000-000000000099',false)");
  const id=checkout.order_id;
  const getOrder=async()=> (await db.query("select *,updated_at::text as version from public.veloce_orders where id=$1",[id])).rows[0];
  const patch=async(input,version)=>(await db.query("select public.veloce_admin_update_order($1,$2,$3)",[id,version??(await getOrder()).version,JSON.stringify(input)]));
  await db.exec("set role authenticated");
  const original=await getOrder();
  assert.equal(original.payment_status,"unpaid");
  await assert.rejects(patch({status:"shipping"}),/Trạng thái/);
  await assert.rejects(patch({total:1}),/Trường cập nhật/);
  await assert.rejects(patch({packed:"yes"}),/đóng gói/);
  await patch({status:"confirmed"});
  assert.ok((await getOrder()).confirmed_at);
  await assert.rejects(patch({internal_note:"stale"},original.version),/vừa thay đổi/);
  await assert.rejects(patch({status:"shipping"}),/Đóng gói/);
  await patch({shipping_carrier:"GHN",tracking_number:"TRACK-123",packed:true});
  await patch({status:"shipping"});
  const shipping=await getOrder();
  assert.ok(shipping.shipped_at);
  assert.deepEqual(shipping.items,original.items);
  assert.equal(shipping.total,original.total);
  await assert.rejects(db.query("select public.veloce_admin_cancel_order($1,$2,'Khách hủy',false)",[id,shipping.version]),/hàng đã về kho/);
  assert.equal((await getOrder()).cancellation_reason,null);
  await patch({payment_status:"paid"});
  await assert.rejects(patch({payment_status:"unpaid"}),/thanh toán/);
  await assert.rejects(patch({payment_status:"refunded"}),/đã hủy/);
  await db.query("select public.veloce_admin_cancel_order($1,$2,'Khách hủy, đã nhận lại hàng',true)",[id,(await getOrder()).version]);
  assert.equal((await getOrder()).status,"cancelled");
  assert.equal((await db.query("select stock from public.veloce_products where id=$1",[productId])).rows[0].stock,10);
  await assert.rejects(db.query("select public.veloce_admin_cancel_order($1,$2,'Hủy lại',true)",[id,(await getOrder()).version]),/kết thúc/);
  await patch({payment_status:"refunded"});
  assert.ok((await getOrder()).refunded_at);
  await assert.rejects(patch({shipping_carrier:"Khác"}),/kết thúc/);
  const events=(await db.query("select * from public.veloce_order_events where order_id=$1",[id])).rows;
  assert.ok(events.length>=7);
  assert.equal(events.filter(e=>e.changes.status?.to==="cancelled").length,1);
  assert.ok(events.some(e=>e.actor_name==="Nhân viên kiểm thử"));
  assert.ok(events.some(e=>e.event_type==="created" && e.actor_name==="Khách hàng"));
  await assert.rejects(db.query("delete from public.veloce_order_events where order_id=$1",[id]),/permission denied/);
  await db.exec("select set_config('test.is_admin','false',false)");
  await assert.rejects(patch({internal_note:"unauthorized"},original.version),/quyền quản trị/);
  assert.equal((await db.query("select * from public.veloce_order_events")).rows.length,0);
  await assert.rejects(db.query("select public.veloce_admin_order_summary()"),/quyền quản trị/);
  await db.exec("reset role");
  await db.exec("select set_config('test.is_admin','true',false)");
  const delivery=(await db.query("select * from public.veloce_place_order('Khách 2','0900000000','Địa chỉ',$1)",[JSON.stringify([{product_id:productId,color:"#000000",size:39,quantity:1}])])).rows[0];
  const deliveryOrder=async()=>(await db.query("select *,updated_at::text as version from public.veloce_orders where id=$1",[delivery.order_id])).rows[0];
  const deliveryPatch=async(input)=>db.query("select public.veloce_admin_update_order($1,$2,$3)",[delivery.order_id,(await deliveryOrder()).version,JSON.stringify(input)]);
  await db.exec("set role authenticated");
  await deliveryPatch({status:"confirmed"});
  await deliveryPatch({packed:true,shipping_carrier:"GHN",tracking_number:"DELIVERY-123"});
  await deliveryPatch({status:"shipping"});
  await deliveryPatch({status:"done"});
  assert.ok((await deliveryOrder()).completed_at);
  assert.equal((await deliveryOrder()).payment_status,"unpaid");
  await assert.rejects(db.query("select public.veloce_admin_cancel_order($1,$2,'Hủy đơn xong',true)",[delivery.order_id,(await deliveryOrder()).version]),/kết thúc/);
  await deliveryPatch({payment_status:"paid"});
  await db.exec("reset role");
  const summary=(await db.query("select public.veloce_admin_order_summary() as summary")).rows[0].summary;
  assert.equal(summary.done,2);
  assert.equal(summary.to_reconcile,1);
  assert.equal(summary.cancelled,1);
  const recoverable=(await db.query("select * from public.veloce_place_order('Khách 3','0900000000','Địa chỉ',$1)",[JSON.stringify([{product_id:productId,color:"#000000",size:39,quantity:1}])])).rows[0];
  await db.query("update public.veloce_products set sizes='{40}',colors=$1 where id=$2",[JSON.stringify([{name:"Đen",hex:"#000000",inventory:[{size:40,quantity:8}]}]),productId]);
  const recoveryBefore=(await db.query("select *,updated_at::text as version from public.veloce_orders where id=$1",[recoverable.order_id])).rows[0];
  const historyBefore=(await db.query("select count(*) as count from public.veloce_order_events where order_id=$1",[recoverable.order_id])).rows[0].count;
  await db.exec("set role authenticated");
  await assert.rejects(db.query("select public.veloce_admin_cancel_order($1,$2,'Khách hủy',false)",[recoverable.order_id,recoveryBefore.version]),/Khôi phục biến thể/);
  const recoveryAfter=(await db.query("select * from public.veloce_orders where id=$1",[recoverable.order_id])).rows[0];
  assert.equal(recoveryAfter.status,"pending");
  assert.equal(recoveryAfter.cancellation_reason,null);
  assert.equal((await db.query("select count(*) as count from public.veloce_order_events where order_id=$1",[recoverable.order_id])).rows[0].count,historyBefore);
  assert.equal((await db.query("select stock from public.veloce_products where id=$1",[productId])).rows[0].stock,8);
  console.log("PASS: legacy unknown payments, anonymous checkout, workflow/packing gates, timestamps, immutable product snapshot, stale-version rejection, safe cancellation/stock restore, payment/refund rules, audit integrity, role denial and summary");
} finally { await db.close(); }
